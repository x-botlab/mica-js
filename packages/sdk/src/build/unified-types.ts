import { generateDeviceTypeScript, type DeviceIR } from '@mica-js/ddl';
import type {
  DevicePropertyDescriptor,
  UnifiedDeviceManifest,
  ValueType,
} from '@mica-js/document/fused';

/** Prefix of the DDL projection embedded in the generated declaration. */
const PROJECTION = 'Mica';

/** Fixed global names of the generated device type environment. */
export const DEVICE_GLOBAL_TYPES = [
  'DeviceProps',
  'DeviceMethods',
  'DeviceEvents',
  'DeviceModelContext',
  'DeviceFactory',
  'DeviceClient',
  'DevicePinId',
] as const;

const DEVICE_MODULE = '@mica-js/sdk/device';

/**
 * Prefix of the aliases generated for `model.types`.
 *
 * Payload type names are author chosen, so they may collide with imported names, the generated
 * `Batch` / `CoreContext` aliases, the global device names or TypeScript keywords. Every public
 * payload name is therefore aliased; refs resolve through the same map.
 */
const PAYLOAD_PREFIX = 'MicaPayload_';

/**
 * Renders `.mica/device.d.ts`.
 *
 * The declaration provides the fixed global names of the device project. Property, method and
 * event shapes come from the manifest; the input, memory and output projections of the core
 * context come from the compiled DDL. The manifest is the only source of public types, so a model
 * implementation and a display implementation share the same names.
 */
export function renderDeviceDeclaration(input: {
  readonly manifest: UnifiedDeviceManifest;
  readonly model?: DeviceIR;
  readonly manifestPath: string;
}): string {
  const { manifest, model } = input;
  const used = new Set<string>([
    'DeviceBatch',
    'DeviceContext',
    'ModelClient',
    'ModelContext',
    'ModelInstance',
  ]);
  const props = renderProperties(manifest, used);
  const methods = renderMethods(manifest);
  const events = renderEvents(manifest);
  const pinIds = Object.keys(manifest.pins ?? {});
  const core =
    model === undefined
      ? [
          'type Batch = DeviceBatch<Record<never, never>>;',
          'type CoreContext = DeviceContext<DeviceProps, Record<never, never>, Record<never, never>>;',
        ]
      : [
          `type Batch = DeviceBatch<${PROJECTION}Outputs>;`,
          `type CoreContext = DeviceContext<DeviceProps, ${PROJECTION}Inputs, ${PROJECTION}Memory>;`,
        ];
  // The DDL projection brings its own type-only imports; merge them into the single import
  // statement below, because two import declarations binding the same name do not compile.
  const projection =
    model === undefined
      ? { imports: [] as string[], lines: [] as string[] }
      : splitProjection(
          generateDeviceTypeScript(model, {
            deviceModule: DEVICE_MODULE,
            name: PROJECTION,
          }).trimEnd(),
        );
  for (const name of projection.imports) used.add(name);
  return [
    `// Generated by @mica-js/sdk from ${input.manifestPath}; do not edit.`,
    '// The global names below are available to every source file of this device project.',
    '',
    'import type {',
    ...[...used].sort().map((name) => `  ${name},`),
    `} from '${DEVICE_MODULE}';`,
    '',
    ...projection.lines,
    ...renderTypes(manifest),
    ...core,
    '',
    'declare global {',
    '  type DeviceProps = {',
    ...props.map((line) => `    ${line}`),
    '  };',
    '  type DeviceMethods = {',
    ...methods.map((line) => `    ${line}`),
    '  };',
    '  type DeviceEvents = {',
    ...events.map((line) => `    ${line}`),
    '  };',
    '  type DeviceModelContext = ModelContext<CoreContext, DeviceProps, DeviceEvents>;',
    '  type DeviceFactory = (context: DeviceModelContext) => ModelInstance<DeviceMethods, Batch>;',
    '  type DeviceClient = ModelClient<DeviceMethods, DeviceEvents>;',
    `  type DevicePinId = ${pinIds.length === 0 ? 'never' : pinIds.map((pin) => JSON.stringify(pin)).join(' | ')};`,
    '}',
    '',
    'export {};',
    '',
  ].join('\n');
}

/** Renders `.mica/tsconfig.json`, which every device project extends. */
export function renderDeviceTypeScriptConfig(sourceDir: string): string {
  const include = `../${sourceDir.replaceAll('\\', '/').replace(/\/+$/, '')}`;
  const config = {
    compilerOptions: {
      target: 'ES2022',
      module: 'ESNext',
      moduleResolution: 'Bundler',
      customConditions: ['source'],
      lib: ['ES2023', 'DOM'],
      types: [],
      strict: true,
      noEmit: true,
      skipLibCheck: true,
      allowArbitraryExtensions: true,
      verbatimModuleSyntax: true,
    },
    files: ['./device.d.ts'],
    include: [include],
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

export function renderModelTypeNamespace(manifest: UnifiedDeviceManifest, name: string): string {
  return [
    `declare namespace ${name} {`,
    ...renderTypes(manifest),
    'export type Methods = {',
    ...renderMethods(manifest),
    '};',
    'export type Events = {',
    ...renderEvents(manifest),
    '};',
    '}',
  ].join('\n');
}

/**
 * Splits the DDL projection into its type-only import names and the remaining module body.
 *
 * The projection is generated by `@mica-js/ddl` and declares one single-line
 * `import type { ... } from '<device module>';` statement.
 */
function splitProjection(source: string): { imports: string[]; lines: string[] } {
  const imports: string[] = [];
  const lines: string[] = [];
  for (const line of source.split('\n')) {
    const match = /^import type \{ (.*) \} from ["'][^"']*["'];$/.exec(line.trim());
    if (match?.[1] !== undefined) {
      for (const name of match[1].split(',')) {
        const trimmed = name.trim();
        if (trimmed.length > 0) imports.push(trimmed);
      }
      continue;
    }
    lines.push(line);
  }
  while (lines.length > 0 && lines[0]?.trim() === '') lines.shift();
  return { imports, lines };
}

function renderProperties(manifest: UnifiedDeviceManifest, used: Set<string>): readonly string[] {
  return Object.entries(manifest.properties ?? {}).map(
    ([name, property]) => `readonly ${name}: ${propertyType(property, used)};`,
  );
}

function propertyType(property: DevicePropertyDescriptor, used: Set<string>): string {
  let type: string;
  switch (property.type) {
    case 'number':
    case 'integer':
      type = 'number';
      break;
    case 'string':
    case 'color':
      type = 'string';
      break;
    case 'boolean':
      type = 'boolean';
      break;
    case 'enum': {
      const options = (property.options ?? []).map((option) => JSON.stringify(option.value));
      type = options.length === 0 ? 'never' : options.join(' | ');
      break;
    }
    case 'image':
    case 'binary':
      used.add('ReadonlyBytes');
      type = 'ReadonlyBytes';
      break;
    case 'firmware':
      used.add('FirmwareImage');
      type = 'FirmwareImage';
      break;
  }
  return property.nullable === true ? `${type} | null` : type;
}

function renderMethods(manifest: UnifiedDeviceManifest): readonly string[] {
  const types = payloadTypes(manifest);
  return Object.entries(manifest.model?.methods ?? {}).map(
    ([name, method]) =>
      `readonly ${name}: (params: ${valueType(method.params, types, 0)}) => ${valueType(method.returns, types, 0)};`,
  );
}

function renderEvents(manifest: UnifiedDeviceManifest): readonly string[] {
  const types = payloadTypes(manifest);
  return Object.entries(manifest.model?.events ?? {}).map(
    ([name, type]) => `readonly ${name}: ${valueType(type, types, 0)};`,
  );
}

/** Public payload type names are ASCII identifiers, so the alias is always valid. */
const PAYLOAD_NAME = /^[A-Za-z][A-Za-z0-9]*$/;

function payloadAlias(name: string): string {
  if (!PAYLOAD_NAME.test(name)) throw new Error(`model.types: invalid payload type name '${name}'`);
  return PAYLOAD_PREFIX + name;
}

function payloadTypes(manifest: UnifiedDeviceManifest): ReadonlySet<string> {
  return new Set(Object.keys(manifest.model?.types ?? {}));
}

/** Named payload types of `model.types`, in manifest order. */
function renderTypes(manifest: UnifiedDeviceManifest): readonly string[] {
  const lines: string[] = [];
  for (const [name, type] of Object.entries(manifest.model?.types ?? {}))
    lines.push(`type ${payloadAlias(name)} = ${valueType(type, payloadTypes(manifest), 0)};`, '');
  return lines;
}

function valueType(type: ValueType, types: ReadonlySet<string>, level: number): string {
  if ('ref' in type) {
    if (!types.has(type.ref)) throw new Error(`model.types: unknown payload type '${type.ref}'`);
    return payloadAlias(type.ref);
  }
  switch (type.type) {
    case 'null':
      return 'null';
    case 'boolean':
      return 'boolean';
    case 'number':
      return 'number';
    case 'string':
      return 'string';
    case 'binary':
      return 'Uint8Array';
    case 'array':
      return `ReadonlyArray<${valueType(type.items, types, level)}>`;
    case 'object': {
      const indent = '  '.repeat(level + 1);
      const optional = type.optional ?? [];
      const members = Object.entries(type.properties).map(
        ([key, item]) =>
          `${indent}readonly ${JSON.stringify(key)}${optional.includes(key) ? '?' : ''}: ${valueType(item, types, level + 1)};`,
      );
      if (type.additionalProperties !== undefined) {
        const index = new Set(
          Object.values(type.properties).map((item) => valueType(item, types, level + 1)),
        );
        if (optional.length > 0) index.add('undefined');
        index.add(valueType(type.additionalProperties, types, level + 1));
        members.push(`${indent}readonly [key: string]: ${[...index].sort().join(' | ')};`);
      }
      if (members.length === 0) return 'Readonly<Record<string, never>>';
      return `{\n${members.join('\n')}\n${'  '.repeat(level)}}`;
    }
  }
}
