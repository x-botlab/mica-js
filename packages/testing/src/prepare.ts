import { mkdir, readFile, writeFile, rename, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { dirname, join, resolve, relative, isAbsolute } from 'node:path';
import { parseFusedDocument, parseStrictJson, deriveFusedTopology } from '@mica-js/document/fused';
import type { UnifiedDeviceManifest } from '@mica-js/document/fused';
import type { MitestConfig } from './config';
import { readDirectoryPackage } from '@mica-js/sdk/fused/node';
import { openDevicePackage } from '@mica-js/sdk/fused';
import { renderTestbenchModule, renderTestTypeScriptConfig } from './prepare-types';

export interface PrepareTestbenchesOptions {
  readonly root: string;
  readonly config: MitestConfig;
  readonly updateLock?: boolean;
}

function record(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function sourceRoot(root: string, documents: readonly string[]): string {
  let common = resolve(root);
  for (const document of documents) {
    for (;;) {
      const child = relative(common, document);
      if (isAbsolute(child))
        throw new Error('Testbench sources must be on the same filesystem volume as the project');
      if (child !== '..' && !child.startsWith('..\\') && !child.startsWith('../')) break;
      common = dirname(common);
    }
  }
  return common;
}

export function testbenchInputs(options: PrepareTestbenchesOptions): readonly string[] {
  return Object.values(options.config.testbenches).flatMap((entry) => [
    resolve(options.root, entry.document),
    ...Object.values(entry.devices).flatMap((path) => [
      resolve(options.root, path, 'release.json'),
      resolve(options.root, path, 'package.json'),
    ]),
  ]);
}

export async function prepareTestbenches(
  options: PrepareTestbenchesOptions,
): Promise<readonly string[]> {
  const outputs = new Map<string, string>();
  const updates = new Map<string, { before: string; after: string }>();
  const common = sourceRoot(
    options.root,
    Object.values(options.config.testbenches).map((entry) => resolve(options.root, entry.document)),
  );
  for (const [name, entry] of Object.entries(options.config.testbenches)) {
    const documentPath = resolve(options.root, entry.document);
    const before = await readFile(documentPath, 'utf8');
    const raw = parseStrictJson(before);
    if (!record(raw) || !record(raw.dependencies))
      throw new Error(`Invalid schematic ${documentPath}`);
    const directories = Object.fromEntries(
      Object.entries(entry.devices).map(([id, path]) => [id, resolve(options.root, path)]),
    );
    const dependencies = { ...raw.dependencies };
    const manifests = new Map<string, UnifiedDeviceManifest>();
    for (const [id, directory] of Object.entries(directories)) {
      const source = await readDirectoryPackage(directory);
      if (source.lock.id !== id)
        throw new Error(`Configured device ${id} is ${source.lock.id} in ${directory}`);
      const verified = await openDevicePackage({ open: async () => source }, source.lock);
      manifests.set(id, verified.manifest);
      if (options.updateLock)
        dependencies[id] = { version: source.lock.version, integrity: source.lock.integrity };
      else {
        const dependency = dependencies[id];
        if (
          !record(dependency) ||
          dependency.version !== source.lock.version ||
          dependency.integrity !== source.lock.integrity
        ) {
          throw new Error(
            `Dependency ${id} differs from ${documentPath}; run mitest prepare --update-lock explicitly`,
          );
        }
      }
    }
    const document = parseFusedDocument({ ...raw, dependencies });
    for (const id of Object.keys(document.dependencies)) {
      if (!manifests.has(id)) throw new Error(`No local device configured for ${id}`);
    }
    deriveFusedTopology(document, manifests);
    const target = join(options.root, '.mitest', 'testbenches', `${name}.ts`);
    outputs.set(
      target,
      renderTestbenchModule({ target, documentPath, document, directories, manifests }),
    );
    if (documentPath.endsWith('.sch')) {
      const declaration = join(
        options.root,
        '.mitest',
        'types',
        relative(common, documentPath).replace(/\.sch$/, '.d.sch.ts'),
      );
      const module = relative(dirname(declaration), target).replaceAll('\\', '/');
      outputs.set(
        declaration,
        `// Generated by mitest; do not edit.\nexport { createTestbench as default } from ${JSON.stringify(module.startsWith('.') ? module : `./${module}`)};\n`,
      );
    }
    if (options.updateLock) {
      const after = JSON.stringify({ ...raw, dependencies }, null, 2) + '\n';
      const previous = updates.get(documentPath);
      if (previous !== undefined && previous.after !== after)
        throw new Error(`Conflicting dependency updates for ${documentPath}`);
      updates.set(documentPath, { before, after });
    }
  }
  outputs.set(
    join(options.root, '.mitest', 'tsconfig.json'),
    renderTestTypeScriptConfig(
      relative(join(options.root, '.mitest'), common).replaceAll('\\', '/'),
    ),
  );
  for (const [file, update] of updates) {
    if ((await readFile(file, 'utf8')) !== update.before)
      throw new Error(`Schematic changed during preparation: ${file}`);
  }
  for (const [file, update] of updates) {
    if (update.before === update.after) continue;
    const temporary = `${file}.${randomUUID()}.tmp`;
    try {
      await writeFile(temporary, update.after, { encoding: 'utf8', flag: 'wx' });
      await rename(temporary, file);
    } finally {
      await rm(temporary, { force: true });
    }
  }
  for (const [file, content] of outputs) {
    await mkdir(dirname(file), { recursive: true });
    let current: string | undefined;
    try {
      current = await readFile(file, 'utf8');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    if (current !== content) await writeFile(file, content, 'utf8');
  }
  return [...outputs.keys()];
}
