import { relative, dirname, isAbsolute } from 'node:path';
import type { FusedDocument, UnifiedDeviceManifest } from '@mica-js/document/fused';
import { renderModelTypeNamespace } from '@mica-js/sdk/prepare';

function fileUrl(from: string, to: string, directory = false): string {
  const path = relative(dirname(from), to);
  if (isAbsolute(path))
    throw new Error('Testbench sources must be on the same filesystem volume as the project');
  const encoded = path
    .replaceAll('\\', '/')
    .split('/')
    .map((segment) => encodeURIComponent(segment))
    .join('/');
  return `new URL(${JSON.stringify((encoded.startsWith('.') ? encoded : `./${encoded}`) + (directory ? '/' : ''))}, import.meta.url)`;
}

export function renderTestbenchModule(input: {
  readonly target: string;
  readonly documentPath: string;
  readonly document: FusedDocument;
  readonly directories: Readonly<Record<string, string>>;
  readonly manifests: ReadonlyMap<string, UnifiedDeviceManifest>;
}): string {
  const definitions: string[] = [];
  const factories = new Map<string, string>();
  for (const [id, manifest] of input.manifests) {
    if (manifest.model === undefined) continue;
    const index = factories.size;
    const namespace = `MicaDevice${index}`;
    const schema = `schema${index}`;
    const factory = `device${index}`;
    factories.set(id, factory);
    definitions.push(renderModelTypeNamespace(manifest, namespace));
    definitions.push(
      `const ${schema} = parseUnifiedManifest(${JSON.stringify(JSON.stringify(manifest))});`,
    );
    const methods: string[] = [];
    const events: string[] = [];
    for (const [name] of Object.entries(manifest.model.methods ?? {})) {
      const decoder = `decode${index}Method${methods.length}`;
      const key = JSON.stringify(name);
      const result = `Result<${namespace}.Methods[${key}]>`;
      definitions.push(`function ${decoder}(value: unknown): ${result} {
  validateModelValue(value, ${schema}.model!.methods![${key}]!.returns, ${schema}.model!.types);
  return value as ${result};
}`);
      methods.push(
        `${key}: async (params: Params<${namespace}.Methods[${key}]>) => ${decoder}(await modelMethod(client, ${key})(params))`,
      );
    }
    for (const name of Object.keys(manifest.model.events ?? {})) {
      const decoder = `decode${index}Event${events.length}`;
      const key = JSON.stringify(name);
      const payload = `${namespace}.Events[${key}]`;
      definitions.push(`function ${decoder}(value: unknown): ${payload} {
  validateModelValue(value, ${schema}.model!.events![${key}]!, ${schema}.model!.types);
  return value as ${payload};
}`);
      events.push(`${key}: modelEvent(client, ${key}, ${decoder})`);
    }
    definitions.push(`function ${factory}(client: RuntimeModelClient) {
  return deviceFacade({ ${methods.join(',\n')} }, { ${events.join(',\n')} });
}`);
  }
  const bindings = input.document.instances.flatMap((instance) => {
    const factory = factories.get(instance.device);
    return instance.designator === undefined || factory === undefined
      ? []
      : [
          `get ${JSON.stringify(instance.designator)}() { return ${factory}(bench.deviceById(${JSON.stringify(instance.id)})); }`,
        ];
  });
  const expected = {
    dependencies: input.document.dependencies,
    instances: input.document.instances.map(({ id, device, designator }) => ({
      id,
      device,
      ...(designator === undefined ? {} : { designator }),
    })),
  };
  return [
    '// Generated by mitest prepare; do not edit.',
    "import type { Params, Result, RuntimeModelClient } from '@mica-js/testing';",
    "import { bindTestbenchDevices, deviceFacade, modelEvent, modelMethod } from '@mica-js/testing';",
    "import { createFileTestbench, parseUnifiedManifest, validateModelValue, type FileTestbenchOptions } from '@mica-js/testing/node';",
    ...definitions,
    `export async function createTestbench(options: FileTestbenchOptions) {
  const bench = await createFileTestbench({
    document: ${fileUrl(input.target, input.documentPath)},
    devices: { ${Object.entries(input.directories)
      .map(([id, path]) => `${JSON.stringify(id)}: ${fileUrl(input.target, path, true)}`)
      .join(',\n')} },
    expected: ${JSON.stringify(expected)},
  }, options);
  return bindTestbenchDevices(bench, { ${bindings.join(',\n')} });
}`,
    'export type CircuitTestbench = Awaited<ReturnType<typeof createTestbench>>;',
    "export type CircuitDevices = CircuitTestbench['devices'];",
    '',
  ].join('\n\n');
}

export function renderTestTypeScriptConfig(sourceRoot = '..'): string {
  return (
    JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2022',
          module: 'ESNext',
          moduleResolution: 'Bundler',
          customConditions: ['source'],
          lib: ['ES2023', 'DOM'],
          types: ['node'],
          strict: true,
          noEmit: true,
          allowImportingTsExtensions: true,
          allowArbitraryExtensions: true,
          rootDirs: [sourceRoot, './types'],
          skipLibCheck: true,
          verbatimModuleSyntax: true,
        },
        include: ['../tests', '../mitest.config.ts', './testbenches/**/*.ts', './types/**/*.ts'],
      },
      null,
      2,
    ) + '\n'
  );
}
