function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  className?: string,
): HTMLElementTagNameMap[K] {
  const element = document.createElement(tag);
  if (className !== undefined) element.className = className;
  return element;
}

function byId<T extends HTMLElement = HTMLElement>(id: string): T {
  const element = document.getElementById(id);
  if (element === null) throw new Error(`HTML 视图缺少 #${id}`);
  return element as T;
}

function group(host: HTMLElement, title: string, meta?: string): HTMLElement {
  const section = el('section', 'group');
  const head = el('div', 'group-head');
  const heading = el('h2', 'group-title');
  heading.textContent = title;
  head.append(heading);
  if (meta !== undefined) {
    const note = el('span', 'group-meta');
    note.textContent = meta;
    head.append(note);
  }
  const body = el('div', 'group-body');
  section.append(head, body);
  host.append(section);
  return body;
}

function readbackLine(parent: HTMLElement, label: string): HTMLElement {
  const line = el('p', 'readback');
  const name = el('span', 'readback-label');
  name.textContent = label;
  const value = el('span', 'readback-value');
  value.textContent = '—';
  line.append(name, value);
  parent.append(line);
  return value;
}

function subhead(parent: HTMLElement, text: string): void {
  const heading = el('p', 'subhead');
  heading.textContent = text;
  parent.append(heading);
}

function fixed(value: number | undefined, digits: number): string {
  return value === undefined ? '—' : value.toFixed(digits);
}

function trimNumber(value: number, digits: number): string {
  return value.toFixed(digits).replace(/\.?0+$/, '');
}

function hexByte(value: number | undefined): string {
  return value === undefined ? '—' : `0x${value.toString(16).padStart(2, '0').toUpperCase()}`;
}

function formatFrequency(value: number | undefined): string {
  return value === undefined ? '—' : `${trimNumber(value / 1e6, 4)} MHz`;
}

function formatClockTime(): string {
  return new Date().toLocaleTimeString('zh-CN', { hour12: false });
}

