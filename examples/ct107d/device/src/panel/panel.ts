const SERIAL_LOG_ROWS = 320;
const SERIAL_ENTRY_BYTES = 32;

interface SerialUiOptions {
  readonly baud: number | undefined;
  readonly hasRead: boolean;
  readonly hasStatus: boolean;
  readonly hasSend: boolean;
  readonly hasTxEvent: boolean;
  readonly hasRxEvent: boolean;
  readonly read: (
    channel: SerialChannelName,
    cursor: number,
  ) => Promise<Invoked<SerialChunkPayload>>;
  readonly status: (channel: SerialChannelName) => Promise<Invoked<SerialStatusPayload>>;
  readonly send: (data: Uint8Array) => Promise<Outcome>;
}

interface SerialChannelUi {
  readonly name: SerialChannelName;
  readonly label: string;
  readonly ledger: SerialLedger;
  readonly log: HTMLElement;
  readonly stats: HTMLElement;
  readonly count: HTMLElement;
  readonly jump: HTMLButtonElement;
  readonly pending: SerialEntry[];
  initialized: boolean;
  frame: number | undefined;
  status: SerialStatusPayload | undefined;
  statusInFlight: boolean;
  statusDirty: boolean;
  visibleBytes: number;
  trimmedRows: number;
  statusReported: boolean;
}

interface SerialUi {
  ingest(name: SerialChannelName, value: SerialDataPayload, simTime: number | undefined): void;
  initialize(): Promise<void>;
  destroy(): void;
}

function buildSerialUi(
  statusHost: HTMLElement,
  sendHost: HTMLElement,
  logsHost: HTMLElement,
  options: SerialUiOptions,
): SerialUi {
  let destroyed = false;
  let now = '';

  const statusLine = el('p', 'serial-line');
  const eventNotes: string[] = [];
  if (!options.hasTxEvent) eventNotes.push('TX 事件未声明');
  if (!options.hasRxEvent) eventNotes.push('RX 事件未声明');
  statusLine.textContent = `8N1${
    options.baud === undefined ? '' : ` · ${options.baud} baud`
  } · 单次 ≤ ${MAX_UART_BYTES} 字节 · 不自动拆包${
    eventNotes.length === 0 ? '' : ` · ${eventNotes.join(' / ')}`
  }`;
  statusHost.append(statusLine);

  const form = el('form', 'send-form');
  form.noValidate = true;
  const modeRow = el('div', 'mode-row');
  modeRow.setAttribute('role', 'radiogroup');
  modeRow.setAttribute('aria-label', '发送格式');
  const utf8Radio = el('input');
  utf8Radio.type = 'radio';
  utf8Radio.name = 'send-mode';
  utf8Radio.value = 'utf8';
  utf8Radio.checked = true;
  const utf8Label = el('label', 'radio-inline');
  utf8Label.append(utf8Radio, document.createTextNode('UTF-8'));
  const hexRadio = el('input');
  hexRadio.type = 'radio';
  hexRadio.name = 'send-mode';
  hexRadio.value = 'hex';
  const hexLabel = el('label', 'radio-inline');
  hexLabel.append(hexRadio, document.createTextNode('HEX'));
  modeRow.append(utf8Label, hexLabel);

  const textLabel = el('label', 'field-label');
  textLabel.htmlFor = 'send-text';
  textLabel.textContent = '发送内容';
  const text = el('textarea', 'send-input');
  text.id = 'send-text';
  text.rows = 3;
  text.spellcheck = false;
  text.autocomplete = 'off';
  text.autocapitalize = 'off';
  text.setAttribute('aria-describedby', 'send-hint send-error');
  const summary = el('div', 'send-summary');
  const count = el('span', 'meta');
  count.textContent = `0 / ${MAX_UART_BYTES} 字节`;
  const preview = el('code', 'send-preview');
  summary.append(count, preview);
  const hint = el('p', 'hint');
  hint.id = 'send-hint';
  const error = el('p', 'field-error');
  error.id = 'send-error';
  error.setAttribute('role', 'alert');
  error.hidden = true;
  const actions = el('div', 'send-actions');
  const sendButton = el('button', 'button button-primary');
  sendButton.type = 'submit';
  sendButton.textContent = '发送';
  const clearButton = el('button', 'button');
  clearButton.type = 'button';
  clearButton.textContent = '清空';
  const sendState = el('span', 'meta');
  sendState.setAttribute('role', 'status');
  actions.append(sendButton, clearButton, sendState);
  form.append(modeRow, textLabel, text, summary, hint, error, actions);
  sendHost.append(form);

  if (!options.hasSend) {
    sendButton.disabled = true;
    clearButton.disabled = true;
    text.disabled = true;
    utf8Radio.disabled = true;
    hexRadio.disabled = true;
    hint.textContent = '模型未声明 sendUart，无法发送。';
    hint.dataset['tone'] = 'error';
  }

  const mode = (): 'utf8' | 'hex' => (hexRadio.checked ? 'hex' : 'utf8');
  const currentPayload = (): PayloadResult =>
    mode() === 'hex' ? parseHexPayload(text.value) : encodeUtf8Payload(text.value);
  const setHint = (): void => {
    if (!options.hasSend) return;
    hint.textContent =
      mode() === 'hex'
        ? '每字节两位十六进制，空白仅作分隔；最多 64 字节；不接受 0x 前缀。'
        : '按 UTF-8 编码后最多 64 字节；换行和中文都按实际字节计数。';
    hint.dataset['tone'] = 'idle';
  };
  let sending = false;

  const validate = (): PayloadResult => {
    const result = currentPayload();
    if (!options.hasSend) return result;
    if (text.value.length === 0) {
      count.textContent = `0 / ${MAX_UART_BYTES} 字节`;
      preview.textContent = '';
      error.hidden = true;
      text.setAttribute('aria-invalid', 'false');
      sendButton.disabled = true;
      return result;
    }
    if (result.ok) {
      count.textContent = `${result.bytes.length} / ${MAX_UART_BYTES} 字节`;
      preview.textContent = formatHexBytes(result.bytes, 24);
      error.hidden = true;
      text.setAttribute('aria-invalid', 'false');
      sendButton.disabled = sending;
    } else {
      count.textContent = `— / ${MAX_UART_BYTES} 字节`;
      preview.textContent = '';
      error.textContent = result.message;
      error.hidden = false;
      text.setAttribute('aria-invalid', 'true');
      sendButton.disabled = true;
    }
    return result;
  };

  const onModeChange = (): void => {
    if (destroyed) return;
    setHint();
    validate();
  };
  utf8Radio.addEventListener('change', onModeChange);
  hexRadio.addEventListener('change', onModeChange);
  text.addEventListener('input', () => {
    if (!destroyed) validate();
  });
  text.addEventListener('keydown', (event) => {
    if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) {
      event.preventDefault();
      form.requestSubmit();
    }
  });
  clearButton.addEventListener('click', () => {
    if (destroyed) return;
    text.value = '';
    sendState.textContent = '';
    validate();
    text.focus();
  });
  form.addEventListener('submit', (event) => {
    event.preventDefault();
    void (async () => {
      if (destroyed || sending || !options.hasSend) return;
      const result = validate();
      if (!result.ok || result.bytes.length === 0) return;
      sending = true;
      sendButton.disabled = true;
      utf8Radio.disabled = true;
      hexRadio.disabled = true;
      text.disabled = true;
      sendState.textContent = '发送中…';
      const outcome = await options.send(result.bytes);
      if (destroyed) return;
      sending = false;
      utf8Radio.disabled = false;
      hexRadio.disabled = false;
      text.disabled = false;
      if (outcome.ok) {
        now = formatClockTime();
        sendState.textContent = `${outcome.note} · ${now}`;
        error.hidden = true;
        text.setAttribute('aria-invalid', 'false');
        validate();
      } else {
        sendState.textContent = '';
        error.textContent = outcome.message;
        error.hidden = false;
        text.setAttribute('aria-invalid', 'true');
        sendButton.disabled = true;
      }
    })();
  });
  setHint();
  validate();

  const channels: Record<SerialChannelName, SerialChannelUi> = {
    uart1Tx: createChannel('uart1Tx', 'TX', '发送记录'),
    uart1Rx: createChannel('uart1Rx', 'RX', '接收记录'),
  };

  function createChannel(name: SerialChannelName, label: string, title: string): SerialChannelUi {
    const block = el('section', 'log-block');
    const head = el('div', 'log-head');
    const heading = el('h3');
    heading.textContent = `${label} · ${title}`;
    const logCount = el('span', 'log-count');
    logCount.textContent = '0 B';
    const jump = el('button', 'button button-small');
    jump.type = 'button';
    jump.textContent = '跳到最新';
    jump.hidden = true;
    const clear = el('button', 'button button-small');
    clear.type = 'button';
    clear.textContent = '清屏';
    clear.setAttribute('title', '只清空显示，不改变模型历史与游标');
    head.append(heading, logCount, jump, clear);
    const stats = el('p', 'log-stats');
    stats.textContent = 'cursor — · 保留 — · 模型丢弃 —';
    const log = el('div', 'log');
    log.setAttribute('role', 'log');
    log.setAttribute('aria-live', 'off');
    log.setAttribute('aria-label', `${label} ${title}`);
    log.tabIndex = 0;
    const empty = el('p', 'log-empty');
    empty.textContent = '等待数据…';
    log.append(empty);
    block.append(head, stats, log);
    logsHost.append(block);

    const channel: SerialChannelUi = {
      name,
      label,
      ledger: new SerialLedger(4096),
      log,
      stats,
      count: logCount,
      jump,
      pending: [],
      initialized: false,
      frame: undefined,
      status: undefined,
      statusInFlight: false,
      statusDirty: false,
      visibleBytes: 0,
      trimmedRows: 0,
      statusReported: false,
    };

    const nearBottom = (): boolean => log.scrollHeight - log.scrollTop - log.clientHeight < 24;
    const scrollToLatest = (): void => {
      log.scrollTop = log.scrollHeight;
      jump.hidden = true;
    };
    log.addEventListener('scroll', () => {
      if (destroyed) return;
      jump.hidden = nearBottom();
    });
    jump.addEventListener('click', scrollToLatest);
    clear.addEventListener('click', () => {
      if (destroyed) return;
      log.replaceChildren();
      const placeholder = el('p', 'log-empty');
      placeholder.textContent = '已清屏；模型历史与游标未改变。';
      log.append(placeholder);
      channel.visibleBytes = 0;
      channel.trimmedRows = 0;
      logCount.textContent = '0 B';
      jump.hidden = true;
    });

    return channel;
  }

  function updateCount(channel: SerialChannelUi): void {
    channel.count.textContent =
      channel.trimmedRows === 0
        ? `${channel.visibleBytes} B`
        : `${channel.visibleBytes} B · 已隐藏 ${channel.trimmedRows} 行`;
  }

  function appendRow(
    channel: SerialChannelUi,
    bytes: Uint8Array | undefined,
    simTime: number | undefined,
    system: string | undefined,
  ): void {
    if (destroyed) return;
    const log = channel.log;
    const placeholder = log.querySelector('.log-empty');
    if (placeholder !== null) placeholder.remove();
    const wasNearBottom =
      log.scrollHeight - log.scrollTop - log.clientHeight < 24 || log.scrollHeight === 0;
    const row = el('div', system === undefined ? 'log-entry' : 'log-system');
    if (system !== undefined) {
      row.textContent = system;
    } else if (bytes !== undefined) {
      const time = el('span', 'log-time');
      time.textContent = formatSimTime(simTime);
      const hex = el('code', 'log-hex');
      hex.textContent = formatHexBytes(bytes);
      const ascii = el('span', 'log-ascii');
      ascii.textContent = formatAsciiPreview(bytes);
      row.append(time, hex, ascii);
      channel.visibleBytes += bytes.length;
    }
    log.append(row);
    while (log.childElementCount > SERIAL_LOG_ROWS) {
      const first = log.firstElementChild;
      if (first === null) break;
      first.remove();
      channel.trimmedRows += 1;
    }
    updateCount(channel);
    if (wasNearBottom) {
      log.scrollTop = log.scrollHeight;
      channel.jump.hidden = true;
    } else {
      channel.jump.hidden = false;
    }
  }

  function appendEntries(
    channel: SerialChannelUi,
    bytes: Uint8Array,
    simTime: number | undefined,
  ): void {
    for (let offset = 0; offset < bytes.length; offset += SERIAL_ENTRY_BYTES) {
      const slice = bytes.subarray(offset, offset + SERIAL_ENTRY_BYTES);
      appendRow(channel, slice, simTime, undefined);
    }
  }

  function appendSystem(channel: SerialChannelUi, text: string): void {
    appendRow(channel, undefined, undefined, text);
  }

  function renderStats(channel: SerialChannelUi): void {
    if (destroyed) return;
    const status = channel.status;
    if (status === undefined) {
      if (!channel.statusReported) {
        channel.stats.textContent = options.hasStatus
          ? 'cursor — · 保留 — · 模型丢弃 —'
          : '模型未声明 getSerialStatus';
      }
      return;
    }
    channel.statusReported = true;
    const extras: string[] = [];
    if (channel.ledger.droppedBytes > 0) extras.push(`补读跳过 ${channel.ledger.droppedBytes}`);
    if (channel.ledger.gapBytes > 0) extras.push(`未接续 ${channel.ledger.gapBytes}`);
    channel.stats.textContent = `next ${status.next} / 保留 ${status.oldest}..${status.next} · 容量 ${
      status.capacity
    } · 模型丢弃 ${status.droppedTotal}${extras.length === 0 ? '' : ` · ${extras.join(' · ')}`}`;
  }

  async function requestStatus(channel: SerialChannelUi): Promise<void> {
    if (destroyed || !options.hasStatus) return;
    if (channel.statusInFlight) {
      channel.statusDirty = true;
      return;
    }
    channel.statusInFlight = true;
    do {
      channel.statusDirty = false;
      const result = await options.status(channel.name);
      if (destroyed) {
        channel.statusInFlight = false;
        return;
      }
      if (result.ok) {
        channel.status = result.value;
        renderStats(channel);
      }
    } while (channel.statusDirty && !destroyed);
    channel.statusInFlight = false;
  }

  function flushChannel(channel: SerialChannelUi): void {
    if (destroyed) return;
    channel.frame = undefined;
    if (!channel.initialized) return;
    const pending = channel.pending.splice(0);
    if (pending.length === 0) return;
    const parts: Uint8Array[] = [];
    let total = 0;
    let simTime: number | undefined;
    let touched = false;
    for (const entry of pending) {
      const ingest = channel.ledger.ingest({ start: entry.cursor, data: entry.data });
      if (ingest.gapBytes > 0) {
        appendSystem(channel, `游标未接续 ${ingest.gapBytes} 字节（实时事件缺口）`);
        touched = true;
      }
      if (ingest.appended.length > 0) {
        parts.push(ingest.appended);
        total += ingest.appended.length;
        simTime = entry.simTime;
        touched = true;
      }
    }
    if (total > 0) {
      const merged = new Uint8Array(total);
      let offset = 0;
      for (const part of parts) {
        merged.set(part, offset);
        offset += part.length;
      }
      appendEntries(channel, merged, simTime);
    }
    if (touched) void requestStatus(channel);
  }

  function scheduleFlush(channel: SerialChannelUi): void {
    if (destroyed || channel.frame !== undefined || !channel.initialized) return;
    channel.frame = requestAnimationFrame(() => flushChannel(channel));
  }

  async function initializeChannel(channel: SerialChannelUi): Promise<void> {
    if (channel.initialized) return;
    if (!options.hasRead) {
      appendSystem(channel, '模型未声明 readSerial；只显示订阅后的实时字节。');
      channel.initialized = true;
      flushChannel(channel);
      void requestStatus(channel);
      return;
    }
    const result = await options.read(channel.name, 0);
    if (destroyed) return;
    channel.initialized = true;
    if (result.ok) {
      const ingest = channel.ledger.ingest({
        start: result.value.start,
        data: result.value.data,
        dropped: result.value.dropped,
      });
      if (result.value.dropped > 0) {
        appendSystem(channel, `补读时模型已裁剪 ${result.value.dropped} 字节更早历史`);
      }
      if (ingest.gapBytes > 0) appendSystem(channel, `补读未接续 ${ingest.gapBytes} 字节`);
      if (ingest.appended.length > 0) {
        appendEntries(channel, ingest.appended, undefined);
      }
    } else {
      appendSystem(channel, `补读历史失败：${result.message}`);
    }
    flushChannel(channel);
    void requestStatus(channel);
  }

  return {
    ingest(name: SerialChannelName, value: SerialDataPayload, simTime: number | undefined) {
      if (destroyed) return;
      const channel = channels[name];
      // The subscription is registered first so nothing after activation is missed. While the
      // history reply is in flight these live chunks wait here; the history is ingested first, so
      // an overlapping live byte is deduplicated instead of making the history look duplicate.
      channel.pending.push({ cursor: value.cursor, data: value.data.slice(), simTime });
      if (channel.initialized) scheduleFlush(channel);
    },
    async initialize() {
      await Promise.all([initializeChannel(channels.uart1Tx), initializeChannel(channels.uart1Rx)]);
    },
    destroy() {
      destroyed = true;
      for (const channel of Object.values(channels)) {
        if (channel.frame !== undefined) {
          cancelAnimationFrame(channel.frame);
          channel.frame = undefined;
        }
      }
      sendButton.disabled = true;
      clearButton.disabled = true;
      text.disabled = true;
      utf8Radio.disabled = true;
      hexRadio.disabled = true;
    },
  };
}

