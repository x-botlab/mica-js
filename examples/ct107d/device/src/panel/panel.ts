function buildAssemblyView(
  host: HTMLElement,
  actions: AssemblyActions,
  capabilities: AssemblyCapabilities,
): AssemblyView {
  const keyGroup = group(host, '按键 · 17 键', '保持组合');
  const keyToolbar = el('div', 'toolbar');
  const keySummary = el('p', 'meta');
  keySummary.textContent = '尚未读取模型状态';
  keySummary.setAttribute('aria-live', 'polite');
  const releaseButton = el('button', 'button button-small');
  releaseButton.type = 'button';
  releaseButton.textContent = '全部释放';
  keyToolbar.append(keySummary, releaseButton);
  keyGroup.append(keyToolbar);

  const resetRow = el('div', 'key-reset-row');
  const keyGrid = el('div', 'key-grid');
  keyGroup.append(resetRow, keyGrid);
  const keyButtons = new Map<KeyName, HTMLButtonElement>();

  const paintKey = (name: KeyName, pressed: boolean | undefined): void => {
    const button = keyButtons.get(name);
    if (button === undefined) return;
    button.setAttribute('aria-pressed', pressed === true ? 'true' : 'false');
    const state = button.querySelector<HTMLElement>('.key-state');
    if (state !== null)
      state.textContent = pressed === undefined ? '未知' : pressed ? '按下' : '松开';
    button.classList.toggle('is-pressed', pressed === true);
  };

  for (const name of KEY_NAMES) {
    const button = el('button', 'key');
    button.type = 'button';
    button.dataset['key'] = name;
    button.disabled = true;
    const label = el('span', 'key-name');
    label.textContent = name;
    const state = el('span', 'key-state');
    state.textContent = '未知';
    button.append(label, state);
    if (name === 'S1') {
      button.classList.add('key-reset');
      button.setAttribute('title', 'S1 接在 VCC 与 RST 之间');
      resetRow.append(button);
    } else {
      keyGrid.append(button);
    }
    keyButtons.set(name, button);
  }
  const keyHint = el('p', 'hint');
  keyHint.textContent = '点击切换并保持按下；可与跳线组合。照片热区释放的键会在下一次事件中同步。';
  keyGroup.append(keyHint);

  const keyStates = new Map<KeyName, boolean>();
  const pendingKeys = new Set<KeyName>();
  let keysAvailable = capabilities.keys;
  let jumpersAvailable = capabilities.jumpers;
  let irAvailable = capabilities.ir;
  let stateKnown = false;
  let destroyed = false;

  const applyKeyDisabled = (): void => {
    for (const [name, button] of keyButtons) {
      button.disabled = destroyed || !keysAvailable || !stateKnown || pendingKeys.has(name);
    }
    releaseButton.disabled = destroyed || !keysAvailable || !stateKnown;
  };
  const paintSummary = (): void => {
    if (!stateKnown) {
      keySummary.textContent = '尚未读取模型状态';
      return;
    }
    const pressed = KEY_NAMES.filter((name) => keyStates.get(name) === true);
    keySummary.textContent =
      pressed.length === 0 ? '模型按住：无' : `模型按住：${pressed.join('、')}`;
    keySummary.dataset['tone'] = pressed.length > 0 ? 'active' : 'idle';
  };

  for (const [name, button] of keyButtons) {
    button.addEventListener('click', () => {
      void (async () => {
        if (destroyed || !keysAvailable || !stateKnown || pendingKeys.has(name)) return;
        const desired = keyStates.get(name) !== true;
        pendingKeys.add(name);
        applyKeyDisabled();
        const outcome = await actions.setSwitch(name, desired);
        if (destroyed) return;
        pendingKeys.delete(name);
        if (outcome.ok) {
          keyStates.set(name, desired);
          paintKey(name, desired);
          paintSummary();
        } else {
          keySummary.textContent = `${name}：${outcome.message}`;
          keySummary.dataset['tone'] = 'error';
        }
        applyKeyDisabled();
      })();
    });
  }

  releaseButton.addEventListener('click', () => {
    void (async () => {
      if (destroyed || !keysAvailable || !stateKnown) return;
      for (const name of KEY_NAMES) if (keyStates.get(name) === true) pendingKeys.add(name);
      applyKeyDisabled();
      const outcome = await actions.releaseAll();
      if (destroyed) return;
      pendingKeys.clear();
      if (outcome.ok) {
        for (const name of KEY_NAMES) {
          keyStates.set(name, false);
          paintKey(name, false);
        }
        paintSummary();
      } else {
        keySummary.textContent = outcome.message;
        keySummary.dataset['tone'] = 'error';
      }
      applyKeyDisabled();
    })();
  });

  const jumperGroup = group(host, '跳线 · 装配', '模型方法 setJumper');
  const jumperFields = new Map<JumperName, HTMLFieldSetElement>();
  const jumperStates = new Map<JumperName, boolean>();
  const pendingJumpers = new Set<JumperName>();
  const jumperMessage = el('p', 'control-state');
  jumperMessage.dataset['tone'] = 'idle';
  jumperMessage.textContent = '尚未读取模型状态';
  jumperMessage.setAttribute('aria-live', 'polite');

  const applyJumperDisabled = (): void => {
    for (const [name, field] of jumperFields) {
      field.disabled = destroyed || !jumpersAvailable || !stateKnown || pendingJumpers.has(name);
    }
  };
  const paintJumper = (name: JumperName, closed: boolean | undefined): void => {
    const field = jumperFields.get(name);
    if (field === undefined) return;
    for (const radio of field.querySelectorAll<HTMLInputElement>('input[type="radio"]')) {
      radio.checked = closed !== undefined && radio.value === String(closed);
    }
  };

  for (const spec of JUMPER_SPECS) {
    const field = el('fieldset', 'jumper');
    const legend = el('legend');
    const legendTitle = el('span', 'jumper-title');
    legendTitle.textContent = spec.title;
    const legendPurpose = el('span', 'jumper-purpose');
    legendPurpose.textContent = spec.purpose;
    legend.append(legendTitle, legendPurpose);
    field.append(legend);
    const options = el('div', 'jumper-options');
    for (const option of spec.options) {
      const label = el('label', 'jumper-option');
      const radio = el('input');
      radio.type = 'radio';
      radio.name = `jumper-${spec.name}`;
      radio.value = String(option.closed);
      radio.addEventListener('change', () => {
        if (radio.checked) void onJumperChange(spec.name, option.closed);
      });
      const text = el('span', 'jumper-option-text');
      const position = el('span', 'jumper-position');
      position.textContent = option.position;
      const title = el('span', 'jumper-option-title');
      title.textContent = option.title;
      const detail = el('span', 'jumper-detail');
      detail.textContent = option.detail;
      text.append(position, title, detail);
      label.append(radio, text);
      options.append(label);
    }
    field.append(options);
    jumperGroup.append(field);
    jumperFields.set(spec.name, field);
  }
  jumperGroup.append(jumperMessage);
  applyJumperDisabled();

  async function onJumperChange(name: JumperName, closed: boolean): Promise<void> {
    if (destroyed || !jumpersAvailable || !stateKnown || pendingJumpers.has(name)) return;
    pendingJumpers.add(name);
    applyJumperDisabled();
    const outcome = await actions.setJumper(name, closed);
    if (destroyed) return;
    pendingJumpers.delete(name);
    if (outcome.ok) {
      jumperStates.set(name, closed);
      paintJumper(name, closed);
      jumperMessage.textContent = `${name} 已切换到 ${closed ? '闭合位置' : '另一位置'}`;
      jumperMessage.dataset['tone'] = 'ok';
    } else {
      paintJumper(name, jumperStates.get(name));
      jumperMessage.textContent = `${name}：${outcome.message}`;
      jumperMessage.dataset['tone'] = 'error';
    }
    applyJumperDisabled();
  }

  const irGroup = group(host, '红外 · 独立源', '显式位号');
  const irButtons = new Map<IrName, HTMLButtonElement>();
  const irReadbacks = new Map<IrName, HTMLElement>();
  const irStates = new Map<IrName, boolean>();
  const pendingIr = new Set<IrName>();
  const irHint = el('p', 'hint');
  irHint.textContent =
    'LD1 / U11 / U20 三个源独立；J2 只决定哪一路接收器进入 P1.1，不会同时驱动三个源。';
  irGroup.append(irHint);

  const applyIrDisabled = (): void => {
    for (const [name, button] of irButtons) {
      button.disabled = destroyed || !irAvailable || !stateKnown || pendingIr.has(name);
    }
  };
  const paintIr = (name: IrName, active: boolean | undefined): void => {
    const button = irButtons.get(name);
    if (button !== undefined) {
      button.setAttribute('aria-pressed', active === true ? 'true' : 'false');
      button.classList.toggle('is-pressed', active === true);
      const state = button.querySelector<HTMLElement>('.switch-state');
      if (state !== null)
        state.textContent = active === undefined ? '未知' : active ? '开启' : '关闭';
    }
    const readback = irReadbacks.get(name);
    if (readback !== undefined) {
      readback.textContent = active === undefined ? '—' : active ? '开启 / 触发' : '关闭 / 未触发';
    }
  };

  for (const spec of IR_SPECS) {
    const row = el('div', 'switch-row');
    const button = el('button', 'switch');
    button.type = 'button';
    button.dataset['ir'] = spec.name;
    button.disabled = true;
    const name = el('span', 'switch-name');
    name.textContent = spec.title;
    const state = el('span', 'switch-state');
    state.textContent = '未知';
    button.append(name, state);
    const detail = el('span', 'switch-detail');
    detail.textContent = spec.detail;
    const readback = el('span', 'switch-readback');
    readback.textContent = `${spec.output}：—`;
    row.append(button, detail, readback);
    irGroup.append(row);
    irButtons.set(spec.name, button);
    irReadbacks.set(spec.name, readback);
    button.addEventListener('click', () => {
      void (async () => {
        if (destroyed || !irAvailable || !stateKnown || pendingIr.has(spec.name)) return;
        const desired = irStates.get(spec.name) !== true;
        pendingIr.add(spec.name);
        applyIrDisabled();
        const outcome = await actions.setIr(spec.name, desired);
        if (destroyed) return;
        pendingIr.delete(spec.name);
        if (outcome.ok) {
          irStates.set(spec.name, desired);
          paintIr(spec.name, desired);
          irHint.textContent =
            'LD1 / U11 / U20 三个源独立；J2 只决定哪一路接收器进入 P1.1，不会同时驱动三个源。';
          irHint.dataset['tone'] = 'idle';
        } else {
          paintIr(spec.name, irStates.get(spec.name));
          irHint.textContent = `${spec.name}：${outcome.message}`;
          irHint.dataset['tone'] = 'error';
        }
        applyIrDisabled();
      })();
    });
  }
  applyIrDisabled();

  return {
    render(state: SnapshotPayload | undefined) {
      if (destroyed) return;
      if (state === undefined) {
        stateKnown = false;
        for (const name of KEY_NAMES) paintKey(name, undefined);
        paintSummary();
        jumperMessage.textContent = '尚未读取模型状态';
        jumperMessage.dataset['tone'] = 'idle';
        for (const name of JUMPER_NAMES) paintJumper(name, undefined);
        for (const name of IR_NAMES) paintIr(name, undefined);
      } else {
        stateKnown = true;
        for (const name of KEY_NAMES) {
          const pressed = state.switches[name];
          keyStates.set(name, pressed);
          paintKey(name, pressed);
        }
        paintSummary();
        for (const name of JUMPER_NAMES) {
          const closed = state.jumpers[name];
          jumperStates.set(name, closed);
          paintJumper(name, closed);
        }
        for (const name of IR_NAMES) {
          const active = state.infrared[name];
          irStates.set(name, active);
          paintIr(name, active);
        }
        jumperMessage.textContent = '位置变更立即重算当前按住的键。';
        jumperMessage.dataset['tone'] = 'idle';
      }
      applyKeyDisabled();
      applyJumperDisabled();
      applyIrDisabled();
    },
    destroy() {
      destroyed = true;
      applyKeyDisabled();
      applyJumperDisabled();
      applyIrDisabled();
    },
  };
}

