async function start(): Promise<void> {
  if (typeof acquireDeviceViewApi !== 'function') {
    showFatal('此页面需要在器件 HTML 视图环境中打开：未找到 acquireDeviceViewApi 桥接。');
    return;
  }
  let api: DeviceViewApi;
  try {
    api = await acquireDeviceViewApi();
  } catch (cause) {
    showFatal(`获取视图桥接失败：${errorMessage(cause)}`);
    return;
  }
  const elements = readElements();
  mountPanel(api, elements);
}

function mountPanel(api: DeviceViewApi, elements: PanelElements): void {
  const model = api.model;
  const unavailable = modelUnavailableReason(model);
  const props = api.props;
  const session = new PanelSession();
  const board = new BoardBootstrap();
  const snapshotEpoch = new RequestEpoch();
  const eepromEpoch = new RequestEpoch();
  const rtcEpoch = new RequestEpoch();
  const refreshEpoch = new RequestEpoch();
  const eepromVersions = new FieldVersions();
  const rtcVersions = new FieldVersions();
  let rtc: RtcPayload | undefined;
  let renderFrame: number | undefined;

  const invoke = async <T>(label: string, task: () => Promise<T>): Promise<Invoked<T>> => {
    if (session.closed) return { ok: false, message: '视图已关闭' };
    const result = await callModel(task);
    if (!result.ok) {
      if (!session.closed) showError(elements, `${label}：${result.message}`);
      return result;
    }
    if (session.closed) return { ok: false, message: '视图已关闭' };
    return result;
  };

  const identityParts = [
    `MCU ${formatFrequency(props.clockFrequency)}`,
    `UART ${props.uartBaud} 8N1`,
    `超声 ${fixed(props.ultrasonicDistanceCm, 1)} cm（属性）`,
  ];
  elements.identity.textContent = identityParts.join(' · ');
  elements.app.setAttribute('aria-busy', 'true');

  elements.errorDismiss.addEventListener('click', () => {
    elements.errorBanner.hidden = true;
  });

  if (unavailable !== undefined) {
    setConnection(elements, 'unavailable', '无运行模型');
    showNotice(elements, unavailable);
    elements.refreshStatus.disabled = true;
  } else {
    setConnection(elements, 'pending', '连接中');
    elements.refreshStatus.disabled = true;
  }

  const inputView = buildInputView(
    elements.inputHost,
    {
      async writeTemperature(value) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return writeOutcome(
          '写入温度',
          () => model.methods.setTemperature({ value }),
          `已下发 ${trimNumber(value, 4)} °C`,
        );
      },
      async writeAnalog(channel, value) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const outcome = await writeOutcome(
          `写入 AIN${channel}`,
          () => model.methods.setAnalogInput({ channel, value }),
          `已下发 AIN${channel} = ${value.toFixed(3)}`,
        );
        if (outcome.ok) board.setAnalog(channel, value);
        return outcome;
      },
      async writeHall(value) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return writeOutcome(
          '写入霍尔磁场',
          () => model.methods.setHallField({ value }),
          `已下发 ${trimNumber(value, 4)} mT`,
        );
      },
      async writeWiper(value) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return writeOutcome(
          '写入滑臂位置',
          () => model.methods.setWiper({ value }),
          `已下发滑臂 ${value.toFixed(3)}`,
        );
      },
      async writeAmplifier(plus, minus) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return writeOutcome(
          '写入差分输入',
          () => model.methods.setAmplifierInputs({ plus, minus }),
          `已下发 IN+ ${trimNumber(plus, 3)} V / IN− ${trimNumber(minus, 3)} V`,
        );
      },
    },
    props,
    {
      temperature: model !== undefined,
      analog: model !== undefined,
      hall: model !== undefined,
      wiper: model !== undefined,
      amplifier: model !== undefined,
    },
  );

  const assemblyView = buildAssemblyView(
    elements.assemblyHost,
    {
      async setSwitch(name, pressed) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const outcome = await writeOutcome(
          `切换 ${name}`,
          () => model.methods.setSwitch({ designator: name, pressed }),
          `${name} ${pressed ? '按下' : '松开'}`,
        );
        if (outcome.ok) board.setSwitch(name, pressed);
        return outcome;
      },
      async setJumper(name, closed) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const outcome = await writeOutcome(
          `切换跳线 ${name}`,
          () => model.methods.setJumper({ designator: name, closed }),
          `${name} ${closed ? '闭合' : '切换'}`,
        );
        if (outcome.ok) board.setJumper(name, closed);
        return outcome;
      },
      async setIr(name, value) {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const outcome = await writeOutcome(
          `切换红外源 ${name}`,
          () => model.methods.setIrCarrier({ designator: name, value }),
          `${name} ${value ? '开启' : '关闭'}`,
        );
        if (outcome.ok) board.setIr(name, value);
        return outcome;
      },
      async releaseAll() {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const readback = board.readback;
        if (readback === undefined) return { ok: false, message: '尚未读取模型状态' };
        const pressed = KEY_NAMES.filter((name) => readback.switches[name] === true);
        if (pressed.length === 0) return { ok: true, note: '当前没有按下的键' };
        const failures: string[] = [];
        for (const name of pressed) {
          const outcome = await writeOutcome(
            `释放 ${name}`,
            () => model.methods.setSwitch({ designator: name, pressed: false }),
            `${name} 松开`,
          );
          if (outcome.ok) board.setSwitch(name, false);
          else failures.push(`${name}：${outcome.message}`);
        }
        return failures.length === 0
          ? { ok: true, note: `已释放 ${pressed.length} 个按键` }
          : { ok: false, message: `部分按键未释放：${failures.join('；')}` };
      },
    },
    {
      keys: model !== undefined,
      jumpers: model !== undefined,
      ir: model !== undefined,
    },
  );

  const statusView = buildStatusView(
    elements.statusReadoutsHost,
    elements.eepromHost,
    elements.rtcHost,
    elements.queryTime,
    elements.refreshStatus,
  );

  const serialView = buildSerialUi(
    elements.serialStatusHost,
    elements.serialSendHost,
    elements.serialLogsHost,
    {
      baud: props.uartBaud,
      hasRead: model !== undefined,
      hasStatus: model !== undefined,
      hasSend: model !== undefined,
      hasTxEvent: model !== undefined,
      hasRxEvent: model !== undefined,
      read: async (channel, cursor) => {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return invoke(`读取 ${channel} 历史`, () => model.methods.readSerial({ channel, cursor }));
      },
      status: async (channel) => {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        return invoke(`读取 ${channel} 状态`, () => model.methods.getSerialStatus({ channel }));
      },
      send: async (data) => {
        if (model === undefined) return { ok: false, message: '模型不可用' };
        const outcome = await invoke('发送串口数据', () => model.methods.sendUart({ data }));
        return outcome.ok
          ? { ok: true, note: `已发送 ${data.length} 字节` }
          : { ok: false, message: outcome.message };
      },
    },
  );

  elements.refreshStatus.addEventListener('click', () => {
    void refreshAll();
  });

  wireTabs();

  session.track(api.onDidClose(() => shutdown()));

  subscribeAll();

  void initialize();

  async function writeOutcome(
    label: string,
    task: () => Promise<unknown>,
    note: string,
  ): Promise<Outcome> {
    const outcome = await invoke(label, task);
    return outcome.ok ? { ok: true, note } : { ok: false, message: outcome.message };
  }

  function scheduleRender(): void {
    if (session.closed || renderFrame !== undefined) return;
    renderFrame = requestAnimationFrame(() => {
      renderFrame = undefined;
      if (!session.closed) renderLive();
    });
  }

  function renderLive(): void {
    const state = board.readback;
    inputView.render(state);
    assemblyView.render(state);
    statusView.render(state);
  }

  function subscribeAll(): void {
    if (model === undefined) return;
    session.track(
      model.events.onDidSignal((event) => {
        if (!session.closed) handleSignal(event.value);
      }),
    );
    session.track(
      model.events.onDidBytes((event) => {
        if (!session.closed) handleBytes(event.value);
      }),
    );
    session.track(
      model.events.onDidAmplifier((event) => {
        if (session.closed) return;
        handleAmplifier(event.value);
      }),
    );
    session.track(
      model.events.onDidUart1Tx((event) => {
        if (!session.closed) serialView.ingest('uart1Tx', event.value, event.simTime);
      }),
    );
    session.track(
      model.events.onDidUart1Rx((event) => {
        if (!session.closed) serialView.ingest('uart1Rx', event.value, event.simTime);
      }),
    );
  }

  function handleSignal(signal: SignalPayload): void {
    if (signal.designator === 'U19' && signal.port === 'running') {
      rtcVersions.bump('rtc.running');
      rtc = { datetime: rtc?.datetime ?? '', running: signal.value !== 0 };
      statusView.renderRtc(rtc, formatClockTime());
    }
    // A signal received while the first snapshot is in flight is queued by the bootstrap and
    // replayed after the reply, instead of being dropped because the view has no state yet.
    if (board.applySignal(signal)) scheduleRender();
  }

  function handleBytes(signal: BytesPayload): void {
    const { designator, port, data } = signal;
    if (designator === 'U4' && port === 'dump') {
      eepromVersions.bump('eeprom');
      statusView.renderEeprom(data, formatClockTime(), '事件更新');
      return;
    }
    if (designator === 'U19' && port === 'datetime') {
      rtcVersions.bump('rtc.datetime');
      rtc = { datetime: new TextDecoder().decode(data), running: rtc?.running ?? false };
      statusView.renderRtc(rtc, formatClockTime());
      return;
    }
    if (board.applyBytes(signal)) scheduleRender();
  }

  function handleAmplifier(amplifier: AmplifierPayload): void {
    if (board.applyAmplifier(amplifier)) scheduleRender();
  }

  async function refreshSnapshot(): Promise<boolean> {
    if (model === undefined) return false;
    const token = snapshotEpoch.start();
    const baseline = board.beginSnapshot();
    const outcome = await invoke('读取状态快照', () => model.methods.getSnapshot(null));
    if (session.closed || !snapshotEpoch.isCurrent(token)) return false;
    if (!outcome.ok) return false;
    if (!board.applySnapshot(outcome.value, baseline)) return false;
    renderLive();
    return true;
  }

  async function refreshEeprom(): Promise<void> {
    if (model === undefined) return;
    const token = eepromEpoch.start();
    const baseline = eepromVersions.snapshot();
    const outcome = await invoke('读取 EEPROM', () => model.methods.getEeprom(null));
    if (session.closed || !eepromEpoch.isCurrent(token)) return;
    if (!outcome.ok) return;
    if (!eepromVersions.isUnchanged('eeprom', baseline)) return;
    statusView.renderEeprom(outcome.value, formatClockTime(), '手动读取');
  }

  async function refreshRtc(): Promise<void> {
    if (model === undefined) return;
    const token = rtcEpoch.start();
    const baseline = rtcVersions.snapshot();
    const outcome = await invoke('读取 RTC', () => model.methods.getRtc(null));
    if (session.closed || !rtcEpoch.isCurrent(token)) return;
    if (!outcome.ok) return;
    const current = rtc;
    rtc =
      current === undefined
        ? outcome.value
        : {
            datetime: rtcVersions.isUnchanged('rtc.datetime', baseline)
              ? outcome.value.datetime
              : current.datetime,
            running: rtcVersions.isUnchanged('rtc.running', baseline)
              ? outcome.value.running
              : current.running,
          };
    statusView.renderRtc(rtc, formatClockTime());
  }

  async function refreshAll(): Promise<void> {
    if (session.closed || model === undefined) return;
    const token = refreshEpoch.start();
    statusView.setBusy(true);
    try {
      await refreshSnapshot();
      if (session.closed || !refreshEpoch.isCurrent(token)) return;
      await refreshEeprom();
      if (session.closed || !refreshEpoch.isCurrent(token)) return;
      await refreshRtc();
      if (session.closed || !refreshEpoch.isCurrent(token)) return;
      statusView.setQueryTime(`最近查询 ${formatClockTime()} · 快照 + EEPROM + RTC`);
    } finally {
      if (!session.closed && refreshEpoch.isCurrent(token)) statusView.setBusy(false);
    }
  }

  async function initialize(): Promise<void> {
    if (model === undefined) {
      elements.app.setAttribute('aria-busy', 'false');
      statusView.render(undefined);
      return;
    }
    setConnection(elements, 'pending', '读取初始状态');
    const token = refreshEpoch.start();
    const applied = await refreshSnapshot();
    if (session.closed) return;
    if (!applied) {
      assemblyView.render(undefined);
      inputView.render(undefined);
      statusView.render(undefined);
    }
    elements.app.setAttribute('aria-busy', 'false');
    setConnection(elements, 'ready', '已连接');
    elements.refreshStatus.disabled = false;
    await serialView.initialize();
    if (session.closed) return;
    await refreshEeprom();
    if (session.closed) return;
    await refreshRtc();
    if (session.closed || !refreshEpoch.isCurrent(token)) return;
    statusView.setQueryTime(`最近查询 ${formatClockTime()} · 初始快照 + EEPROM + RTC`);
  }

  function wireTabs(): void {
    const tabs = Array.from(document.querySelectorAll<HTMLButtonElement>('[role="tab"]'));
    const panels = Array.from(document.querySelectorAll<HTMLElement>('[role="tabpanel"]'));
    if (tabs.length === 0 || panels.length === 0) return;
    const activate = (tab: HTMLButtonElement, focus = false): void => {
      for (const current of tabs) {
        const selected = current === tab;
        current.setAttribute('aria-selected', selected ? 'true' : 'false');
        current.tabIndex = selected ? 0 : -1;
      }
      for (const panel of panels) panel.hidden = panel.id !== tab.getAttribute('aria-controls');
      if (focus) tab.focus();
    };
    for (const tab of tabs)
      tab.addEventListener('click', () => {
        activate(tab);
      });
    const tablist = tabs[0]?.parentElement;
    tablist?.addEventListener('keydown', (event) => {
      const index = tabs.findIndex((tab) => tab.getAttribute('aria-selected') === 'true');
      if (index < 0) return;
      let next = index;
      if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
      else if (event.key === 'ArrowLeft') next = (index - 1 + tabs.length) % tabs.length;
      else if (event.key === 'Home') next = 0;
      else if (event.key === 'End') next = tabs.length - 1;
      else return;
      event.preventDefault();
      const target = tabs[next];
      if (target !== undefined) activate(target, true);
    });
    const initial = tabs[0];
    if (initial !== undefined) activate(initial);
  }

  function shutdown(): void {
    if (session.closed) return;
    refreshEpoch.invalidate();
    snapshotEpoch.invalidate();
    eepromEpoch.invalidate();
    rtcEpoch.invalidate();
    board.close();
    if (renderFrame !== undefined) cancelAnimationFrame(renderFrame);
    renderFrame = undefined;
    serialView.destroy();
    inputView.destroy();
    assemblyView.destroy();
    statusView.destroy();
    try {
      session.close();
    } catch (cause) {
      console.error('[@mica-js/example-ct107d] 控制面板清理失败', cause);
    }
    disableAll(elements.app);
    elements.app.setAttribute('aria-busy', 'false');
    setConnection(elements, 'closed', '已关闭');
    showNotice(elements, '视图已关闭；模型订阅与本地计时已释放。');
  }
}

if (typeof document !== 'undefined') {
  void start().catch((cause: unknown) => {
    showFatal(`控制面板初始化失败：${errorMessage(cause)}`);
  });
}
