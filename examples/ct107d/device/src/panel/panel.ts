interface NumberControlSpec {
  readonly id: string;
  readonly label: string;
  readonly unit: string;
  readonly min: number;
  readonly max: number;
  readonly step: number;
  readonly initial: number;
  readonly range?: boolean;
  readonly hint: string;
  readonly state: string;
  readonly writable: boolean;
  readonly write: (value: number) => Promise<Outcome>;
}

interface NumberControl {
  readonly root: HTMLElement;
  sync(value: number): void;
  setEnabled(enabled: boolean): void;
  destroy(): void;
}

function numberControl(parent: HTMLElement, spec: NumberControlSpec): NumberControl {
  const root = el('div', 'control');
  const head = el('div', 'control-head');
  const label = el('label', 'control-label');
  label.htmlFor = spec.id;
  label.textContent = spec.label;
  const unit = el('span', 'control-unit');
  unit.textContent = spec.unit;
  head.append(label, unit);

  const line = el('div', spec.range === true ? 'control-line has-range' : 'control-line');
  const bounds: NumberBounds = { label: spec.label, min: spec.min, max: spec.max };
  let range: HTMLInputElement | undefined;
  if (spec.range === true) {
    range = el('input', 'range');
    range.type = 'range';
    range.min = String(spec.min);
    range.max = String(spec.max);
    range.step = String(spec.step);
    range.value = String(spec.initial);
    range.setAttribute('aria-label', `${spec.label}滑块`);
    line.append(range);
  }
  const number = el('input', 'input-number');
  number.id = spec.id;
  number.type = 'number';
  number.min = String(spec.min);
  number.max = String(spec.max);
  number.step = String(spec.step);
  number.value = String(spec.initial);
  number.inputMode = 'decimal';
  number.autocomplete = 'off';
  number.setAttribute('aria-describedby', `${spec.id}-hint ${spec.id}-state`);
  line.append(number);

  const writeButton = el('button', 'button button-small');
  writeButton.type = 'button';
  writeButton.textContent = '写入';
  writeButton.setAttribute('aria-label', `写入${spec.label}`);
  line.append(writeButton);

  const hint = el('p', 'hint');
  hint.id = `${spec.id}-hint`;
  hint.textContent = spec.hint;
  const state = el('p', 'control-state');
  state.id = `${spec.id}-state`;
  state.dataset['tone'] = 'idle';
  state.textContent = spec.state;
  state.setAttribute('aria-live', 'polite');

  root.append(head, line, hint, state);
  parent.append(root);

  let touched = false;
  let enabled = spec.writable;
  let destroyed = false;

  const setState = (text: string, tone: 'idle' | 'ok' | 'error'): void => {
    state.textContent = text;
    state.dataset['tone'] = tone;
  };
  const applyEnabled = (): void => {
    number.disabled = destroyed || !enabled;
    if (range !== undefined) range.disabled = destroyed || !enabled;
    writeButton.disabled = destroyed || !enabled;
  };
  const syncNumber = (value: number): void => {
    number.value = String(value);
    if (range !== undefined) range.value = String(value);
  };

  range?.addEventListener('input', () => {
    touched = true;
    if (range !== undefined) number.value = range.value;
  });
  number.addEventListener('input', () => {
    touched = true;
    if (range !== undefined && Number.isFinite(Number(number.value))) range.value = number.value;
  });
  writeButton.addEventListener('click', () => {
    void (async () => {
      if (destroyed || !enabled) return;
      const parsed = parseBoundedNumber(number.value, bounds);
      if (!parsed.ok) {
        setState(parsed.message, 'error');
        return;
      }
      writeButton.disabled = true;
      setState('写入中…', 'idle');
      const outcome = await spec.write(parsed.value);
      if (destroyed) return;
      applyEnabled();
      if (!outcome.ok) {
        setState(outcome.message, 'error');
        return;
      }
      touched = false;
      syncNumber(parsed.value);
      setState(outcome.note, 'ok');
    })();
  });

  if (!spec.writable) setState('模型未声明对应方法', 'error');
  applyEnabled();

  return {
    root,
    sync(value: number) {
      if (touched || destroyed) return;
      syncNumber(value);
    },
    setEnabled(next: boolean) {
      enabled = next;
      applyEnabled();
    },
    destroy() {
      destroyed = true;
      applyEnabled();
    },
  };
}

