type PendingAction =
  | { readonly kind: 'signal'; readonly value: SignalPayload }
  | { readonly kind: 'bytes'; readonly value: BytesPayload }
  | { readonly kind: 'amplifier'; readonly value: AmplifierPayload }
  | {
      readonly kind: 'mutation';
      readonly fields: readonly string[];
      readonly update: (snapshot: SnapshotPayload) => SnapshotPayload;
    };

function isKeyName(value: string): value is KeyName {
  return (KEY_NAMES as readonly string[]).includes(value);
}

/** Field-wise merge: only leaves whose revision is unchanged accept the reply. */
function mergeRecord<T extends object>(
  versions: FieldVersions,
  baseline: ReadonlyMap<string, number>,
  prefix: string,
  current: T,
  reply: T,
): T {
  const merged = { ...current };
  for (const key of Object.keys(reply) as (keyof T)[]) {
    if (versions.isUnchanged(`${prefix}.${String(key)}`, baseline)) merged[key] = reply[key];
  }
  return merged;
}

function mergeSnapshot(
  current: SnapshotPayload,
  reply: SnapshotPayload,
  baseline: ReadonlyMap<string, number>,
  versions: FieldVersions,
): SnapshotPayload {
  const analog = reply.pcf8591.analog.map((value, index) =>
    versions.isUnchanged(`pcf8591.analog.${index}`, baseline)
      ? value
      : (current.pcf8591.analog[index] ?? value),
  );
  return {
    ...current,
    latches: mergeRecord(versions, baseline, 'latches', current.latches, reply.latches),
    relay: freshValue(versions, baseline, 'relay', current.relay, reply.relay),
    buzzer: freshValue(versions, baseline, 'buzzer', current.buzzer, reply.buzzer),
    hall: freshValue(versions, baseline, 'hall', current.hall, reply.hall),
    amplifier: mergeRecord(versions, baseline, 'amplifier', current.amplifier, reply.amplifier),
    temperature: mergeRecord(
      versions,
      baseline,
      'temperature',
      current.temperature,
      reply.temperature,
    ),
    lm386: mergeRecord(versions, baseline, 'lm386', current.lm386, reply.lm386),
    switches: mergeRecord(versions, baseline, 'switches', current.switches, reply.switches),
    jumpers: mergeRecord(versions, baseline, 'jumpers', current.jumpers, reply.jumpers),
    infrared: mergeRecord(versions, baseline, 'infrared', current.infrared, reply.infrared),
    decoder: mergeRecord(versions, baseline, 'decoder', current.decoder, reply.decoder),
    uln2003: mergeRecord(versions, baseline, 'uln2003', current.uln2003, reply.uln2003),
    pcf8591: {
      ...mergeRecord(versions, baseline, 'pcf8591', current.pcf8591, reply.pcf8591),
      analog,
    },
    displays: reply.displays,
    leds: reply.leds,
    ledStates: reply.ledStates,
    ne555: reply.ne555,
  };
}

export class BoardBootstrap {
  #readback: SnapshotPayload | undefined;
  #versions = new FieldVersions();
  #pending: PendingAction[] = [];
  #closed = false;

  get readback(): SnapshotPayload | undefined {
    return this.#readback;
  }

  get closed(): boolean {
    return this.#closed;
  }

  close(): void {
    this.#closed = true;
    this.#pending.length = 0;
  }

  /** Revision baseline captured before a snapshot request leaves the view. */
  beginSnapshot(): ReadonlyMap<string, number> {
    return this.#versions.snapshot();
  }

  /**
   * Applies one snapshot reply.
   *
   * The first successful reply establishes the state and replays every event buffered while it was
   * in flight. Later replies merge field by field against the baseline. A closed bootstrap rejects
   * the reply, so a snapshot request that resolves after `onDidClose` cannot repopulate the panel.
   */
  applySnapshot(reply: SnapshotPayload, baseline: ReadonlyMap<string, number>): boolean {
    if (this.#closed) return false;
    if (this.#readback === undefined) {
      this.#readback = reply;
      const pending = this.#pending.splice(0);
      for (const action of pending) this.#applyNow(action);
      return true;
    }
    this.#readback = mergeSnapshot(this.#readback, reply, baseline, this.#versions);
    return true;
  }

  applySignal(signal: SignalPayload): boolean {
    return this.#dispatch({ kind: 'signal', value: signal });
  }

  applyBytes(signal: BytesPayload): boolean {
    return this.#dispatch({ kind: 'bytes', value: signal });
  }

  applyAmplifier(amplifier: AmplifierPayload): boolean {
    return this.#dispatch({ kind: 'amplifier', value: amplifier });
  }

  /** Applies a local control write (also queued before the first snapshot). */
  applyLocal(
    fields: readonly string[],
    update: (snapshot: SnapshotPayload) => SnapshotPayload,
  ): boolean {
    return this.#dispatch({ kind: 'mutation', fields, update });
  }

  setSwitch(name: KeyName, pressed: boolean): boolean {
    return this.applyLocal([`switches.${name}`], (snapshot) => {
      const switches = { ...snapshot.switches };
      switches[name] = pressed;
      return { ...snapshot, switches };
    });
  }

  setJumper(name: JumperName, closed: boolean): boolean {
    return this.applyLocal([`jumpers.${name}`], (snapshot) => {
      const jumpers = { ...snapshot.jumpers };
      jumpers[name] = closed;
      return { ...snapshot, jumpers };
    });
  }

  setIr(name: IrName, active: boolean): boolean {
    return this.applyLocal([`infrared.${name}`], (snapshot) => {
      const infrared = { ...snapshot.infrared };
      infrared[name] = active;
      return { ...snapshot, infrared };
    });
  }

  setAnalog(channel: number, value: number): boolean {
    return this.applyLocal([`pcf8591.analog.${channel}`], (snapshot) => {
      const analog = [...snapshot.pcf8591.analog];
      analog[channel] = value;
      return { ...snapshot, pcf8591: { ...snapshot.pcf8591, analog } };
    });
  }

  #dispatch(action: PendingAction): boolean {
    if (this.#closed) return false;
    if (this.#readback === undefined) {
      this.#pending.push(action);
      return true;
    }
    this.#applyNow(action);
    return true;
  }

  #applyNow(action: PendingAction): void {
    if (action.kind === 'signal') this.#applySignal(action.value);
    else if (action.kind === 'bytes') this.#applyBytes(action.value);
    else if (action.kind === 'amplifier') {
      this.#update(
        ['amplifier.position', 'amplifier.gain', 'amplifier.outputVoltage'],
        (snapshot) => ({
          ...snapshot,
          amplifier: action.value,
        }),
      );
    } else this.#update(action.fields, action.update);
  }

  #update(fields: readonly string[], update: (snapshot: SnapshotPayload) => SnapshotPayload): void {
    if (this.#readback === undefined) return;
    this.#readback = update(this.#readback);
    for (const field of fields) this.#versions.bump(field);
  }

  #applySignal(signal: SignalPayload): void {
    const { designator, port, value } = signal;
    if (designator === 'U6' && port === 'latch') this.#setLatch('U6', value);
    else if (designator === 'U7' && port === 'latch') this.#setLatch('U7', value);
    else if (designator === 'U8' && port === 'latch') this.#setLatch('U8', value);
    else if (designator === 'U9' && port === 'latch') this.#setLatch('U9', value);
    else if (designator === 'K1' && port === 'energized')
      this.#update(['relay'], (snapshot) => ({ ...snapshot, relay: value !== 0 }));
    else if (designator === 'SP1' && port === 'active')
      this.#update(['buzzer'], (snapshot) => ({ ...snapshot, buzzer: value !== 0 }));
    else if (designator === 'U21' && port === 'active')
      this.#update(['hall'], (snapshot) => ({ ...snapshot, hall: value !== 0 }));
    else if (designator === 'U14' && port === 'active')
      this.#update(['lm386.active'], (snapshot) => ({
        ...snapshot,
        lm386: { active: value !== 0 },
      }));
    else if (designator === 'U24' && port === 'select')
      this.#update(['decoder.select'], (snapshot) => ({
        ...snapshot,
        decoder: { ...snapshot.decoder, select: value },
      }));
    else if (designator === 'U24' && port === 'enabled')
      this.#update(['decoder.enabled'], (snapshot) => ({
        ...snapshot,
        decoder: { ...snapshot.decoder, enabled: value !== 0 },
      }));
    else if (designator === 'U10' && port === 'mask')
      this.#update(['uln2003.mask'], (snapshot) => ({
        ...snapshot,
        uln2003: { ...snapshot.uln2003, mask: value },
      }));
    else if (designator === 'U5' && port === 'temperatureOut')
      this.#update(['temperature.converted', 'temperature.value'], (snapshot) => ({
        ...snapshot,
        temperature: { converted: true, value },
      }));
    else if (designator === 'LD1' && port === 'carrier') this.setIr('LD1', value !== 0);
    else if (designator === 'U11' && port === 'receiving') this.setIr('U11', value !== 0);
    else if (designator === 'U20' && port === 'receiving') this.setIr('U20', value !== 0);
    else if (designator === 'J13' && port === 'closedState') this.setJumper('J13', value !== 0);
    else if (designator === 'J5' && port === 'closedState') this.setJumper('J5', value !== 0);
    else if (designator === 'J3' && port === 'closedState') this.setJumper('J3', value !== 0);
    else if (designator === 'J2' && port === 'closedState2') this.setJumper('J2', value !== 0);
    else if (isKeyName(designator) && (port === 'pressed' || port === 'press'))
      this.setSwitch(designator, value !== 0);
  }

  #applyBytes(signal: BytesPayload): void {
    const { designator, port, data } = signal;
    if (designator === 'U24' && port === 'code')
      this.#update(['decoder.code'], (snapshot) => ({
        ...snapshot,
        decoder: { ...snapshot.decoder, code: new TextDecoder().decode(data) },
      }));
    else if (designator === 'U10' && port === 'channels')
      this.#update(['uln2003.channels'], (snapshot) => ({
        ...snapshot,
        uln2003: { ...snapshot.uln2003, channels: new TextDecoder().decode(data) },
      }));
  }

  #setLatch(name: keyof SnapshotPayload['latches'], value: number): void {
    this.#update([`latches.${name}`], (snapshot) => {
      const latches = { ...snapshot.latches };
      latches[name] = value;
      return { ...snapshot, latches };
    });
  }
}

