/**
 * STC15F2K60S2 的指令耗时表（单位：1T 系统时钟）。
 *
 * 数据来自手册第 5.2 节「完整指令集对照表」的 STC15 列：传统 8051 的一条机器周期是
 * 12 个时钟，STC15 的 STC-Y5 内核是 1T，同样一条指令只需 1–6 个时钟。表里没有列出的
 * 变体（SUBB A,Rn、MOVX、MOVC A,@A+DPTR、保留操作码）按同族指令的规律取值，
 * 并在对应分组上注明。
 */

const cycles = new Uint8Array(256).fill(1);

const set = (opcodes: readonly number[], value: number): void => {
  for (const opcode of opcodes) cycles[opcode] = value;
};

const range = (from: number, to: number): number[] =>
  Array.from({ length: to - from + 1 }, (_, index) => from + index);

// 算术运算
set([0x24, 0x25, 0x26, 0x27], 2);
set(range(0x28, 0x2f), 1);
set([0x34, 0x35, 0x36, 0x37], 2);
set(range(0x38, 0x3f), 1);
// SUBB A,Rn 在表里缺行，与 ADD/ADDC 的寄存器形式一致取 1。
set([0x94, 0x95, 0x96, 0x97], 2);
set(range(0x98, 0x9f), 1);
set([0x04, 0xa3], 1);
set([0x05, 0x06, 0x07], 3);
set(range(0x08, 0x0f), 2);
set([0x14], 1);
set([0x15, 0x16, 0x17], 3);
set(range(0x18, 0x1f), 2);
set([0xa4], 2);
set([0x84], 6);
set([0xd4], 3);

// 逻辑运算
set([0x54, 0x55, 0x56, 0x57], 2);
set(range(0x58, 0x5f), 1);
set([0x52, 0x53], 3);
set([0x44, 0x45, 0x46, 0x47], 2);
set(range(0x48, 0x4f), 1);
set([0x42, 0x43], 3);
set([0x64, 0x65, 0x66, 0x67], 2);
set(range(0x68, 0x6f), 1);

// 累加器操作
set([0xe4, 0xf4, 0x23, 0x33, 0x03, 0x13, 0xc4], 1);
set([0xc3, 0xd3, 0xb3], 1);

// 数据传送
set(range(0xe8, 0xef), 1);
set([0xe5], 2);
set([0xe6, 0xe7], 2);
set([0x74], 2);
set(range(0xf8, 0xff), 1);
set(range(0xa8, 0xaf), 3);
set(range(0x78, 0x7f), 2);
set([0xf5], 2);
set(range(0x88, 0x8f), 2);
set([0x85], 3);
set([0x86, 0x87], 3);
set([0x75], 3);
set([0xf6, 0xf7], 2);
set([0xa6, 0xa7], 3);
set([0x76, 0x77], 2);
set([0x90], 3);
// MOVC/MOVX 在表里只列出 MOVC A,@A+PC=4；其余按同类取 4 / 3。
set([0x83, 0x93], 4);
set([0xe0, 0xe2, 0xe3, 0xf0, 0xf2, 0xf3], 3);
set([0xc0], 3);
set([0xd0], 2);
set(range(0xc8, 0xcf), 2);
set([0xc5], 3);
set([0xc6, 0xc7, 0xd6, 0xd7], 3);

// 位操作
set([0x82, 0xb0, 0x72, 0xa0, 0xa2], 2);
set([0x92, 0xc2, 0xd2, 0xb2], 3);

// 控制转移
set(range(0x01, 0x01), 3);
set([0x21, 0x41, 0x61, 0x81, 0xa1, 0xc1, 0xe1], 3);
set([0x11], 3);
set([0x31, 0x51, 0x71, 0x91, 0xb1, 0xd1, 0xf1], 3);
set([0x02, 0x12], 4);
set([0x22, 0x32], 4);
set([0x80], 3);
set([0x73], 5);
set([0x40, 0x50], 3);
set([0x60, 0x70], 4);
set([0x20, 0x30, 0x10], 5);
set([0xb5], 5);
set([0xb4], 4);
set(range(0xb8, 0xbf), 4);
set([0xb6, 0xb7], 5);
set(range(0xd8, 0xdf), 4);
set([0xd5], 5);

// 空操作与保留操作码
set([0x00, 0xa5], 1);

export function instructionCycles(opcode: number): number {
  return cycles[opcode & 0xff] ?? 1;
}
